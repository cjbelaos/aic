// Generates the versioned schema migration from schema-map.mjs.
//   node scripts/migration/generate-schema.mjs > supabase/migrations/<ts>_aic_schema.sql
import { SCHEMA, TABLES, FOREIGN_KEYS, INDEXES, parseCols, SQL_TYPES } from "./schema-map.mjs";

const S = SCHEMA;
const q = (id) => (/^[a-z_][a-z0-9_]*$/.test(id) && !["group", "user", "order", "key", "value", "text", "date", "type"].includes(id) ? id : `"${id}"`);
const pkOf = new Map(TABLES.map((t) => [t.table, t.pk ?? "id"]));
const out = [];
const emit = (s = "") => out.push(s);

emit(`-- Generated by scripts/migration/generate-schema.mjs from schema-map.mjs. Do not edit by hand.`);
emit(`-- AIC operational schema (Sheets → PostgreSQL migration, plan §2).`);
emit();
emit(`create schema if not exists ${S};`);
emit(`revoke all on schema ${S} from public;`);
emit(`do $$ begin`);
emit(`  if exists (select 1 from pg_roles where rolname = 'anon') then execute 'revoke all on schema ${S} from anon'; end if;`);
emit(`  if exists (select 1 from pg_roles where rolname = 'authenticated') then execute 'revoke all on schema ${S} from authenticated'; end if;`);
emit(`  if not exists (select 1 from pg_roles where rolname = 'aic_app') then create role aic_app nologin; end if;`);
emit(`end $$;`);
emit(`grant usage on schema ${S} to aic_app;`);
emit();
emit(`-- Audit stamping. The app sets the actor per transaction:  select set_config('aic.actor', '<userId>', true);`);
emit(`-- Background jobs use 'system:<job>'. Writes without an actor fail. The importer (not aic_app) may set`);
emit(`-- aic.importing = 'on' to keep source audit values exactly as captured (null where the Sheet had none).`);
emit(`create or replace function ${S}.audit_stamp() returns trigger language plpgsql as $$`);
emit(`declare actor text := nullif(current_setting('aic.actor', true), '');`);
emit(`begin`);
emit(`  if current_setting('aic.importing', true) = 'on' and current_user <> 'aic_app' then return new; end if;`);
emit(`  if actor is null then raise exception 'aic.actor is not set for this transaction' using errcode = 'P0001'; end if;`);
emit(`  if tg_op = 'INSERT' then`);
emit(`    new.created_at := now(); new.created_by := actor; new.source_row := null; new.import_raw := null;`);
emit(`  else`);
emit(`    new.created_at := old.created_at; new.created_by := old.created_by;`);
emit(`    new.source_row := old.source_row; new.import_raw := old.import_raw;`);
emit(`  end if;`);
emit(`  new.updated_at := now(); new.updated_by := actor;`);
emit(`  return new;`);
emit(`end $$;`);
emit();
emit(`-- One row per import run: snapshot identity, counts and the validation report (no record contents).`);
emit(`create table if not exists ${S}.import_batches (`);
emit(`  batch_id text primary key, snapshot_sha256 text not null, captured_at timestamptz not null,`);
emit(`  started_at timestamptz not null default now(), promoted_at timestamptz, counts jsonb, report jsonb,`);
emit(`  source_row integer, import_raw jsonb, created_by text, created_at timestamptz, updated_by text, updated_at timestamptz`);
emit(`);`);
emit();

const allTables = [{ table: "import_batches" }, ...TABLES];
for (const t of TABLES) {
  const cols = t.special === "grid"
    ? [{ column: "row_no", type: "i" }, { column: "cells", type: "j" }]
    : parseCols(t).filter((c) => !c.audit);
  const lines = [];
  if (!t.pk) lines.push(`id bigint generated always as identity primary key`, `line_no integer not null`);
  for (const c of cols) lines.push(`${q(c.column)} ${SQL_TYPES[c.type]}${c.column === t.pk ? " not null" : ""}`);
  lines.push(`source_row integer`, `import_raw jsonb`, `created_by text`, `created_at timestamptz`, `updated_by text`, `updated_at timestamptz`);
  if (t.pk) lines.push(`primary key (${q(t.pk)})`);
  for (const u of t.unique || []) lines.push(`unique (${u.split(",").map(q).join(", ")})`);
  emit(`-- ${t.tab}`);
  emit(`create table ${S}.${t.table} (\n  ${lines.join(",\n  ")}\n);`);
  if (t.secret) emit(`comment on column ${S}.${t.table}.${t.secret[0]} is 'secret: never select into logs or exports';`);
}
emit();
for (const t of allTables) {
  emit(`alter table ${S}.${t.table} enable row level security;`);
  emit(`create trigger audit_stamp before insert or update on ${S}.${t.table} for each row execute function ${S}.audit_stamp();`);
}
emit();
emit(`-- Relationships`);
const indexed = new Set();
for (const [from, to] of FOREIGN_KEYS) {
  const [table, column] = from.split(".");
  const name = `${table}_${column}_fkey`.slice(0, 63);
  emit(`alter table ${S}.${table} add constraint ${name} foreign key (${q(column)}) references ${S}.${to} (${q(pkOf.get(to))});`);
  if (pkOf.get(table) !== column && !indexed.has(from)) {
    indexed.add(from);
    emit(`create index on ${S}.${table} (${q(column)});`);
  }
}
emit();
emit(`-- Register list and search paths`);
for (const ix of INDEXES) emit(`create index on ${S}.${ix.replace(/^(\w+)\((.*)\)$/, (_, tb, c) => `${tb} (${c})`)};`);
emit();
emit(`grant select, insert, update, delete on all tables in schema ${S} to aic_app;`);
emit(`revoke all on ${S}.import_batches from aic_app;`);
emit(`grant select on ${S}.import_batches to aic_app;`);
emit(`alter default privileges in schema ${S} grant select, insert, update, delete on tables to aic_app;`);
process.stdout.write(out.join("\n") + "\n");
