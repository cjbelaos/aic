// Generates src/lib/db/sheetColumns.generated.ts: for every imported tab, the SQL that returns each
// sheet header's value in the text format the Sheets API gave the app. Timestamp formats are detected
// from the snapshot (ISO text vs "YYYY-MM-DD HH:MM:SS" wall clock, UTC or Manila).
//   node scripts/migration/emit-sheet-columns.mjs <snapshotDir>
import { readFileSync, writeFileSync } from "node:fs";
import { TABLES, FOREIGN_KEYS, parseCols } from "./schema-map.mjs";

const snap = JSON.parse(readFileSync(`${process.argv[2]}/database.json`, "utf8")).tabs;
const fks = new Set(FOREIGN_KEYS.map(([from]) => from));
const quote = (id) => (/^[a-z_][a-z0-9_]*$/.test(id) && !["group", "user", "order", "key", "value", "text", "date", "type"].includes(id) ? id : `"${id}"`);
const sqlString = (s) => `'${s.replace(/'/g, "''")}'`;

function timestampFormat(tab, header, type) {
  const { formatted } = snap[tab];
  const k = (formatted[0] || []).map((h) => String(h ?? "").trim()).indexOf(header);
  let isoCount = 0, wallCount = 0;
  for (const row of formatted.slice(1)) {
    const v = String(row[k] ?? "").trim();
    if (/^\d{4}-\d{2}-\d{2}T/.test(v)) isoCount++;
    else if (/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}/.test(v)) wallCount++;
  }
  if (wallCount > isoCount) return type === "tm" ? "manila" : "utc";
  return "iso";
}

const out = {};
for (const t of TABLES) {
  if (t.special) continue;
  const columns = {};
  const headers = (snap[t.tab].formatted[0] || []).map((h) => String(h ?? "").trim());
  for (const c of parseCols(t)) {
    const name = quote(c.column);
    const key = c.header ?? `#${c.index}`; // positional columns are keyed by index
    let sql;
    // import_raw keys follow the importer: the sheet header, or "#<index>" when the header is blank.
    const rawKey = c.header ?? (headers[c.index] || `#${c.index}`);
    if (fks.has(`${t.table}.${c.column}`)) sql = `coalesce(${name}::text, import_raw->>${sqlString(rawKey)}, '')`;
    else if (c.type === "b") sql = `case when ${name} then 'TRUE' when not ${name} then 'FALSE' else '' end`;
    else if (c.type === "ts" || c.type === "tm") {
      const fmt = timestampFormat(t.tab, c.header ?? headers[c.index], c.type);
      sql = fmt === "iso"
        ? `coalesce(to_char(${name} at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'), '')`
        : `coalesce(to_char(${name} at time zone '${fmt === "manila" ? "Asia/Manila" : "UTC"}', 'YYYY-MM-DD HH24:MI:SS'), '')`;
    } else if (c.type === "j") sql = `coalesce(${name}::text, '')`;
    else sql = `coalesce(${name}::text, '')`;
    columns[key] = sql;
  }
  out[t.tab] = { table: `aic.${t.table}`, headers, columns };
}

const body = `// Generated by scripts/migration/emit-sheet-columns.mjs. Do not edit by hand.
// For each sheet tab: its PostgreSQL table and, per header, the SQL that yields the value as the Sheets API returned it.
// \`headers\` is the live tab's header row (column A first); \`columns\` is keyed by header, or "#<index>" for unnamed columns.
export const SHEET_COLUMNS: Record<string, { table: string; headers: string[]; columns: Record<string, string> }> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync("src/lib/db/sheetColumns.generated.ts", body);
console.log(`wrote ${Object.keys(out).length} tabs to src/lib/db/sheetColumns.generated.ts`);
